-- Hacker News import (plan section 10, cold start).
--
-- System accounts are clearly labeled curators run by Vouch itself, such as "Hacker News".
-- Nobody can sign in as one, and the daily vouch limit does not apply to them.
alter table users add column is_system boolean not null default false;

-- One row per HN comment that recommended a video: who said it, when, and their words.
-- The excerpt is a verbatim quote, checked against the comment before it is stored.
create table hn_mentions (
  comment_id  bigint primary key check (comment_id > 0),
  resource_id uuid not null references resources(id) on delete cascade,
  author      text not null,
  posted_at   timestamptz not null,
  excerpt     text check (char_length(excerpt) <= 280),
  imported_at timestamptz not null default now()
);
create index hn_mentions_resource_idx on hn_mentions (resource_id, posted_at desc);

-- Lists generated by an importer carry a stable key, so a re-import rebuilds them in place
-- instead of creating duplicates. User-made lists leave it null.
alter table lists add column system_key text;
create unique index lists_system_key_idx on lists (system_key) where system_key is not null;
